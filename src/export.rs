use std::fs;
use std::path::{Path, PathBuf};

use crate::{CaptureError, ImpulseMatrix, Result};

#[derive(Clone, Debug)]
pub struct ExportedBundle {
    pub config_path: PathBuf,
    pub wav_paths: Vec<PathBuf>,
}

#[derive(Clone, Debug)]
pub struct ExportedCaptureBundle {
    pub equalizer_apo_config_path: PathBuf,
    pub camilladsp_config_path: PathBuf,
    pub wav_paths: Vec<PathBuf>,
}

/// Export the captured matrix once and write configurations for both supported
/// convolution engines.
pub fn export_capture_bundle(
    output_directory: &Path,
    matrix: &ImpulseMatrix,
) -> Result<ExportedCaptureBundle> {
    fs::create_dir_all(output_directory)?;

    let file_names = matrix_wav_file_names(matrix);
    let wav_paths = write_matrix_wavs(output_directory, matrix, &file_names)?;

    let bundle_name = bundle_name(output_directory);
    let equalizer_apo_config_path =
        output_directory.join(format!("{bundle_name}-equalizer-apo.txt"));
    fs::write(
        &equalizer_apo_config_path,
        render_equalizer_apo_config(matrix, &file_names)?,
    )?;

    let camilladsp_config_path = output_directory.join(format!("{bundle_name}-camilladsp.yml"));
    fs::write(
        &camilladsp_config_path,
        render_camilladsp_config(matrix, &file_names)?,
    )?;

    Ok(ExportedCaptureBundle {
        equalizer_apo_config_path,
        camilladsp_config_path,
        wav_paths,
    })
}

pub fn export_equalizer_apo_bundle(
    output_directory: &Path,
    matrix: &ImpulseMatrix,
) -> Result<ExportedBundle> {
    fs::create_dir_all(output_directory)?;

    let file_names = matrix_wav_file_names(matrix);
    let wav_paths = write_matrix_wavs(output_directory, matrix, &file_names)?;

    let config_path = output_directory.join(format!(
        "{}-equalizer-apo.txt",
        bundle_name(output_directory)
    ));
    fs::write(
        &config_path,
        render_equalizer_apo_config(matrix, &file_names)?,
    )?;

    Ok(ExportedBundle {
        config_path,
        wav_paths,
    })
}

pub fn export_camilladsp_bundle(
    output_directory: &Path,
    matrix: &ImpulseMatrix,
) -> Result<ExportedBundle> {
    fs::create_dir_all(output_directory)?;

    let file_names = matrix_wav_file_names(matrix);
    let wav_paths = write_matrix_wavs(output_directory, matrix, &file_names)?;

    let config_path =
        output_directory.join(format!("{}-camilladsp.yml", bundle_name(output_directory)));
    fs::write(&config_path, render_camilladsp_config(matrix, &file_names)?)?;

    Ok(ExportedBundle {
        config_path,
        wav_paths,
    })
}

pub fn render_equalizer_apo_config(
    matrix: &ImpulseMatrix,
    wav_file_names: &[String],
) -> Result<String> {
    if wav_file_names.len() != matrix.input_channels().len() {
        return Err(CaptureError::InvalidSettings(format!(
            "expected {} WAV file names, got {}",
            matrix.input_channels().len(),
            wav_file_names.len()
        )));
    }

    let path_count = matrix
        .input_channels()
        .len()
        .checked_mul(matrix.output_channels().len())
        .ok_or_else(|| {
            CaptureError::InvalidSettings("too many matrix paths for Equalizer APO".into())
        })?;
    if path_count > 36 * 36 {
        return Err(CaptureError::InvalidSettings(
            "Equalizer APO export supports at most 1296 matrix paths".into(),
        ));
    }

    let mut config = String::from(
        "# Generated by rust-impulse-response.\n\
         # Each virtual channel represents one input-to-output transfer path.\n",
    );

    let copies = matrix
        .input_channels()
        .iter()
        .enumerate()
        .flat_map(|(input, source)| {
            (0..matrix.output_channels().len()).map(move |output| {
                let path = input * matrix.output_channels().len() + output;
                format!("{}={source}", virtual_channel_name(path))
            })
        })
        .collect::<Vec<_>>();
    config.push_str(&format!("Copy: {}\n\n", copies.join(" ")));

    for (input, file_name) in wav_file_names.iter().enumerate() {
        let virtual_channels = (0..matrix.output_channels().len())
            .map(|output| virtual_channel_name(input * matrix.output_channels().len() + output))
            .collect::<Vec<_>>();
        config.push_str(&format!("Channel: {}\n", virtual_channels.join(" ")));
        config.push_str(&format!("Convolution: {file_name}\n\n"));
    }

    let output_mixes = matrix
        .output_channels()
        .iter()
        .enumerate()
        .map(|(output, destination)| {
            let terms = (0..matrix.input_channels().len())
                .map(|input| virtual_channel_name(input * matrix.output_channels().len() + output))
                .collect::<Vec<_>>();
            format!("{destination}={}", terms.join("+"))
        })
        .collect::<Vec<_>>();
    config.push_str(&format!("Copy: {}\n", output_mixes.join(" ")));
    config.push_str(&format!(
        "Channel: {}\n",
        matrix.output_channels().join(" ")
    ));

    Ok(config)
}

/// Render a complete CamillaDSP configuration using native PipeWire nodes.
///
/// CamillaDSP applies a convolution filter to one pipeline channel at a time,
/// so the first mixer expands every input into one channel per matrix path.
/// Each path selects its output channel from the corresponding multichannel
/// WAV, and the final mixer sums those paths into the physical outputs.
pub fn render_camilladsp_config(
    matrix: &ImpulseMatrix,
    wav_file_names: &[String],
) -> Result<String> {
    validate_wav_file_names(matrix, wav_file_names)?;

    let input_count = matrix.input_channels().len();
    let output_count = matrix.output_channels().len();
    let path_count = input_count
        .checked_mul(output_count)
        .ok_or_else(|| CaptureError::InvalidSettings("too many CamillaDSP matrix paths".into()))?;

    let mut config = String::from(
        "# Generated by rust-impulse-response.\n\
         # Native PipeWire template for Linux and SteamOS.\n\
         # Route audio into camilladsp-capture and route camilladsp-playback to your output.\n\
         ---\n\
         title: \"Captured software filter\"\n\
         description: \"Full input-to-output convolution matrix\"\n",
    );
    config.push_str("devices:\n");
    config.push_str(&format!("  samplerate: {}\n", matrix.sample_rate()));
    config.push_str(&format!(
        "  chunksize: {}\n",
        recommended_camilladsp_chunksize(matrix.sample_rate())
    ));
    config.push_str("  multithreaded: true\n");
    config.push_str("  capture:\n");
    config.push_str("    type: PipeWire\n");
    config.push_str(&format!("    channels: {input_count}\n"));
    config.push_str("    node_name: camilladsp-capture\n");
    config.push_str("    node_description: CamillaDSP Capture\n");
    config.push_str("    labels:\n");
    for label in matrix.input_channels() {
        config.push_str(&format!("      - {}\n", yaml_string(label)));
    }
    config.push_str("  playback:\n");
    config.push_str("    type: PipeWire\n");
    config.push_str(&format!("    channels: {output_count}\n"));
    config.push_str("    node_name: camilladsp-playback\n");
    config.push_str("    node_description: CamillaDSP Playback\n\n");

    config.push_str("mixers:\n");
    config.push_str("  inputs_to_matrix_paths:\n");
    config.push_str("    channels:\n");
    config.push_str(&format!("      in: {input_count}\n"));
    config.push_str(&format!("      out: {path_count}\n"));
    config.push_str("    mapping:\n");
    for input in 0..input_count {
        for output in 0..output_count {
            let path = input * output_count + output;
            config.push_str(&format!("      - dest: {path}\n"));
            config.push_str("        sources:\n");
            config.push_str(&format!("          - channel: {input}\n"));
            config.push_str("            gain: 0\n");
        }
    }
    config.push_str("  matrix_paths_to_outputs:\n");
    config.push_str("    channels:\n");
    config.push_str(&format!("      in: {path_count}\n"));
    config.push_str(&format!("      out: {output_count}\n"));
    config.push_str("    mapping:\n");
    for output in 0..output_count {
        config.push_str(&format!("      - dest: {output}\n"));
        config.push_str("        sources:\n");
        for input in 0..input_count {
            let path = input * output_count + output;
            config.push_str(&format!("          - channel: {path}\n"));
            config.push_str("            gain: 0\n");
        }
    }
    config.push('\n');

    config.push_str("filters:\n");
    for (input, file_name) in wav_file_names.iter().enumerate() {
        for output in 0..output_count {
            config.push_str(&format!("  {}:\n", camilladsp_filter_name(input, output)));
            config.push_str("    type: Conv\n");
            config.push_str("    parameters:\n");
            config.push_str("      type: Wav\n");
            config.push_str(&format!("      filename: {}\n", yaml_string(file_name)));
            config.push_str(&format!("      channel: {output}\n"));
        }
    }
    config.push('\n');

    config.push_str("pipeline:\n");
    config.push_str("  - type: Mixer\n");
    config.push_str("    name: inputs_to_matrix_paths\n");
    for input in 0..input_count {
        for output in 0..output_count {
            let path = input * output_count + output;
            config.push_str("  - type: Filter\n");
            config.push_str(&format!("    channels: [{path}]\n"));
            config.push_str("    names:\n");
            config.push_str(&format!(
                "      - {}\n",
                camilladsp_filter_name(input, output)
            ));
        }
    }
    config.push_str("  - type: Mixer\n");
    config.push_str("    name: matrix_paths_to_outputs\n");

    Ok(config)
}

/// Equalizer APO channel identifiers are limited to three characters. A `V`
/// prefix plus two base-36 digits provides 1296 collision-free virtual paths.
fn virtual_channel_name(path: usize) -> String {
    const DIGITS: &[u8; 36] = b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    let high = DIGITS[path / 36] as char;
    let low = DIGITS[path % 36] as char;
    format!("V{high}{low}")
}

fn matrix_wav_file_names(matrix: &ImpulseMatrix) -> Vec<String> {
    matrix
        .input_channels()
        .iter()
        .enumerate()
        .map(|(index, channel)| format!("from-{:02}-{}.wav", index + 1, safe_name(channel)))
        .collect()
}

fn bundle_name(output_directory: &Path) -> String {
    let name = output_directory
        .file_name()
        .and_then(|name| name.to_str())
        .map(safe_name)
        .unwrap_or_default();
    let name = name
        .split('-')
        .filter(|part| !part.is_empty())
        .collect::<Vec<_>>()
        .join("-");

    if name
        .chars()
        .any(|character| character.is_ascii_alphanumeric())
    {
        name
    } else {
        "captured-filter".into()
    }
}

fn write_matrix_wavs(
    output_directory: &Path,
    matrix: &ImpulseMatrix,
    file_names: &[String],
) -> Result<Vec<PathBuf>> {
    let mut wav_paths = Vec::with_capacity(file_names.len());
    for (input, file_name) in file_names.iter().enumerate() {
        let path = output_directory.join(file_name);
        write_input_wav(&path, matrix, input)?;
        wav_paths.push(path);
    }
    Ok(wav_paths)
}

fn write_input_wav(path: &Path, matrix: &ImpulseMatrix, input: usize) -> Result<()> {
    let channels = u16::try_from(matrix.output_channels().len()).map_err(|_| {
        CaptureError::InvalidSettings("too many output channels for a WAV file".into())
    })?;
    let spec = hound::WavSpec {
        channels,
        sample_rate: matrix.sample_rate(),
        bits_per_sample: 32,
        sample_format: hound::SampleFormat::Float,
    };
    let mut writer = hound::WavWriter::create(path, spec)?;
    for frame in 0..matrix.response_frames() {
        for output in 0..matrix.output_channels().len() {
            writer.write_sample(matrix.responses()[input][output][frame])?;
        }
    }
    writer.finalize()?;
    Ok(())
}

fn validate_wav_file_names(matrix: &ImpulseMatrix, wav_file_names: &[String]) -> Result<()> {
    if wav_file_names.len() != matrix.input_channels().len() {
        return Err(CaptureError::InvalidSettings(format!(
            "expected {} WAV file names, got {}",
            matrix.input_channels().len(),
            wav_file_names.len()
        )));
    }
    Ok(())
}

fn camilladsp_filter_name(input: usize, output: usize) -> String {
    format!("matrix_path_in_{input}_out_{output}")
}

fn recommended_camilladsp_chunksize(sample_rate: u32) -> u32 {
    match sample_rate {
        0..=48_000 => 1024,
        48_001..=96_000 => 2048,
        _ => 4096,
    }
}

fn yaml_string(value: &str) -> String {
    let mut quoted = String::with_capacity(value.len() + 2);
    quoted.push('"');
    for character in value.chars() {
        match character {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            '\r' => quoted.push_str("\\r"),
            '\t' => quoted.push_str("\\t"),
            character if character.is_control() => {
                quoted.push_str(&format!("\\u{:04X}", character as u32));
            }
            character => quoted.push(character),
        }
    }
    quoted.push('"');
    quoted
}

fn safe_name(channel: &str) -> String {
    let result = channel
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '-' || character == '_' {
                character
            } else {
                '-'
            }
        })
        .collect::<String>();
    if result.is_empty() {
        "channel".into()
    } else {
        result
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stereo_matrix() -> ImpulseMatrix {
        ImpulseMatrix::new(
            48_000,
            vec!["L".into(), "R".into()],
            vec!["L".into(), "R".into()],
            vec![
                vec![vec![1.0, 0.0], vec![0.0, 0.5]],
                vec![vec![0.0, 0.25], vec![1.0, 0.0]],
            ],
        )
        .unwrap()
    }

    #[test]
    fn config_routes_a_complete_stereo_matrix() {
        let config = render_equalizer_apo_config(
            &stereo_matrix(),
            &["from-L.wav".into(), "from-R.wav".into()],
        )
        .unwrap();

        assert!(config.contains("V00=L"));
        assert!(config.contains("V01=L"));
        assert!(config.contains("V02=R"));
        assert!(config.contains("V03=R"));
        assert!(config.contains("Channel: V00 V01\nConvolution: from-L.wav"));
        assert!(config.contains("Copy: L=V00+V02 R=V01+V03"));
    }

    #[test]
    fn camilladsp_config_routes_a_complete_stereo_matrix() {
        let config = render_camilladsp_config(
            &stereo_matrix(),
            &["from-L.wav".into(), "from-R.wav".into()],
        )
        .unwrap();

        assert!(config.contains("samplerate: 48000"));
        assert!(config.contains("type: PipeWire"));
        assert!(config.contains("in: 2\n      out: 4"));
        assert!(config.contains(
            "matrix_path_in_1_out_0:\n    type: Conv\n    parameters:\n      type: Wav\n      filename: \"from-R.wav\"\n      channel: 0"
        ));
        assert!(config.contains(
            "- type: Filter\n    channels: [3]\n    names:\n      - matrix_path_in_1_out_1"
        ));
        assert!(config.contains(
            "- dest: 1\n        sources:\n          - channel: 1\n            gain: 0\n          - channel: 3\n            gain: 0"
        ));
    }

    #[test]
    fn camilladsp_config_quotes_channel_labels_for_yaml() {
        let matrix = ImpulseMatrix::new(
            48_000,
            vec!["left: \"main\"\n".into()],
            vec!["output".into()],
            vec![vec![vec![1.0]]],
        )
        .unwrap();

        let config = render_camilladsp_config(&matrix, &["filter.wav".into()]).unwrap();

        assert!(config.contains("      - \"left: \\\"main\\\"\\n\""));
    }

    #[test]
    fn config_filenames_use_a_portable_output_directory_name() {
        assert_eq!(
            bundle_name(Path::new("exports/My Speakers (48 kHz)")),
            "My-Speakers-48-kHz"
        );
        assert_eq!(bundle_name(Path::new(".")), "captured-filter");
    }

    #[test]
    fn writes_float_wavs_with_one_channel_per_output() {
        let unique = format!(
            "rust-ir-export-test-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        );
        let directory = std::env::temp_dir().join(&unique);
        let bundle = export_equalizer_apo_bundle(&directory, &stereo_matrix()).unwrap();

        assert_eq!(
            bundle.config_path.file_name().unwrap(),
            format!("{unique}-equalizer-apo.txt").as_str()
        );
        assert_eq!(bundle.wav_paths.len(), 2);
        let reader = hound::WavReader::open(&bundle.wav_paths[0]).unwrap();
        assert_eq!(reader.spec().channels, 2);
        assert_eq!(reader.spec().sample_rate, 48_000);
        assert_eq!(reader.spec().sample_format, hound::SampleFormat::Float);
        assert_eq!(reader.duration(), 2);
        assert!(bundle.config_path.exists());

        fs::remove_dir_all(directory).unwrap();
    }

    #[test]
    fn writes_configs_for_both_supported_engines() {
        let unique = format!(
            "rust-ir-all-export-test-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        );
        let directory = std::env::temp_dir().join(&unique);
        let bundle = export_capture_bundle(&directory, &stereo_matrix()).unwrap();

        assert_eq!(
            bundle.equalizer_apo_config_path.file_name().unwrap(),
            format!("{unique}-equalizer-apo.txt").as_str()
        );
        assert_eq!(
            bundle.camilladsp_config_path.file_name().unwrap(),
            format!("{unique}-camilladsp.yml").as_str()
        );
        assert!(bundle.equalizer_apo_config_path.exists());
        assert!(bundle.camilladsp_config_path.exists());
        assert_eq!(bundle.wav_paths.len(), 2);

        fs::remove_dir_all(directory).unwrap();
    }
}
