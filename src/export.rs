use std::fs;
use std::path::{Path, PathBuf};

use crate::{CaptureError, ImpulseMatrix, Result};

#[derive(Clone, Debug)]
pub struct ExportedBundle {
    pub config_path: PathBuf,
    pub wav_paths: Vec<PathBuf>,
}

pub fn export_equalizer_apo_bundle(
    output_directory: &Path,
    matrix: &ImpulseMatrix,
) -> Result<ExportedBundle> {
    fs::create_dir_all(output_directory)?;

    let file_names = matrix
        .input_channels()
        .iter()
        .enumerate()
        .map(|(index, channel)| format!("from-{:02}-{}.wav", index + 1, safe_name(channel)))
        .collect::<Vec<_>>();

    let mut wav_paths = Vec::with_capacity(file_names.len());
    for (input, file_name) in file_names.iter().enumerate() {
        let path = output_directory.join(file_name);
        write_input_wav(&path, matrix, input)?;
        wav_paths.push(path);
    }

    let config_path = output_directory.join("equalizer-apo.txt");
    fs::write(
        &config_path,
        render_equalizer_apo_config(matrix, &file_names)?,
    )?;

    Ok(ExportedBundle {
        config_path,
        wav_paths,
    })
}

pub fn render_equalizer_apo_config(
    matrix: &ImpulseMatrix,
    wav_file_names: &[String],
) -> Result<String> {
    if wav_file_names.len() != matrix.input_channels().len() {
        return Err(CaptureError::InvalidSettings(format!(
            "expected {} WAV file names, got {}",
            matrix.input_channels().len(),
            wav_file_names.len()
        )));
    }

    let path_count = matrix
        .input_channels()
        .len()
        .checked_mul(matrix.output_channels().len())
        .ok_or_else(|| {
            CaptureError::InvalidSettings("too many matrix paths for Equalizer APO".into())
        })?;
    if path_count > 36 * 36 {
        return Err(CaptureError::InvalidSettings(
            "Equalizer APO export supports at most 1296 matrix paths".into(),
        ));
    }

    let mut config = String::from(
        "# Generated by rust-impulse-response.\n\
         # Each virtual channel represents one input-to-output transfer path.\n",
    );

    let copies = matrix
        .input_channels()
        .iter()
        .enumerate()
        .flat_map(|(input, source)| {
            (0..matrix.output_channels().len()).map(move |output| {
                let path = input * matrix.output_channels().len() + output;
                format!("{}={source}", virtual_channel_name(path))
            })
        })
        .collect::<Vec<_>>();
    config.push_str(&format!("Copy: {}\n\n", copies.join(" ")));

    for (input, file_name) in wav_file_names.iter().enumerate() {
        let virtual_channels = (0..matrix.output_channels().len())
            .map(|output| virtual_channel_name(input * matrix.output_channels().len() + output))
            .collect::<Vec<_>>();
        config.push_str(&format!("Channel: {}\n", virtual_channels.join(" ")));
        config.push_str(&format!("Convolution: {file_name}\n\n"));
    }

    let output_mixes = matrix
        .output_channels()
        .iter()
        .enumerate()
        .map(|(output, destination)| {
            let terms = (0..matrix.input_channels().len())
                .map(|input| virtual_channel_name(input * matrix.output_channels().len() + output))
                .collect::<Vec<_>>();
            format!("{destination}={}", terms.join("+"))
        })
        .collect::<Vec<_>>();
    config.push_str(&format!("Copy: {}\n", output_mixes.join(" ")));
    config.push_str(&format!(
        "Channel: {}\n",
        matrix.output_channels().join(" ")
    ));

    Ok(config)
}

/// Equalizer APO channel identifiers are limited to three characters. A `V`
/// prefix plus two base-36 digits provides 1296 collision-free virtual paths.
fn virtual_channel_name(path: usize) -> String {
    const DIGITS: &[u8; 36] = b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    let high = DIGITS[path / 36] as char;
    let low = DIGITS[path % 36] as char;
    format!("V{high}{low}")
}

fn write_input_wav(path: &Path, matrix: &ImpulseMatrix, input: usize) -> Result<()> {
    let channels = u16::try_from(matrix.output_channels().len()).map_err(|_| {
        CaptureError::InvalidSettings("too many output channels for a WAV file".into())
    })?;
    let spec = hound::WavSpec {
        channels,
        sample_rate: matrix.sample_rate(),
        bits_per_sample: 32,
        sample_format: hound::SampleFormat::Float,
    };
    let mut writer = hound::WavWriter::create(path, spec)?;
    for frame in 0..matrix.response_frames() {
        for output in 0..matrix.output_channels().len() {
            writer.write_sample(matrix.responses()[input][output][frame])?;
        }
    }
    writer.finalize()?;
    Ok(())
}

fn safe_name(channel: &str) -> String {
    let result = channel
        .chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() || character == '-' || character == '_' {
                character
            } else {
                '-'
            }
        })
        .collect::<String>();
    if result.is_empty() {
        "channel".into()
    } else {
        result
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stereo_matrix() -> ImpulseMatrix {
        ImpulseMatrix::new(
            48_000,
            vec!["L".into(), "R".into()],
            vec!["L".into(), "R".into()],
            vec![
                vec![vec![1.0, 0.0], vec![0.0, 0.5]],
                vec![vec![0.0, 0.25], vec![1.0, 0.0]],
            ],
        )
        .unwrap()
    }

    #[test]
    fn config_routes_a_complete_stereo_matrix() {
        let config = render_equalizer_apo_config(
            &stereo_matrix(),
            &["from-L.wav".into(), "from-R.wav".into()],
        )
        .unwrap();

        assert!(config.contains("V00=L"));
        assert!(config.contains("V01=L"));
        assert!(config.contains("V02=R"));
        assert!(config.contains("V03=R"));
        assert!(config.contains("Channel: V00 V01\nConvolution: from-L.wav"));
        assert!(config.contains("Copy: L=V00+V02 R=V01+V03"));
    }

    #[test]
    fn writes_float_wavs_with_one_channel_per_output() {
        let unique = format!(
            "rust-ir-export-test-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        );
        let directory = std::env::temp_dir().join(unique);
        let bundle = export_equalizer_apo_bundle(&directory, &stereo_matrix()).unwrap();

        assert_eq!(bundle.wav_paths.len(), 2);
        let reader = hound::WavReader::open(&bundle.wav_paths[0]).unwrap();
        assert_eq!(reader.spec().channels, 2);
        assert_eq!(reader.spec().sample_rate, 48_000);
        assert_eq!(reader.spec().sample_format, hound::SampleFormat::Float);
        assert_eq!(reader.duration(), 2);
        assert!(bundle.config_path.exists());

        fs::remove_dir_all(directory).unwrap();
    }
}
